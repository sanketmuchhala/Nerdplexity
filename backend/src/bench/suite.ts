import { readFileSync } from 'fs';
import path from 'path';
import type { BenchCategory } from '@app/types';
import type { ToolSpec } from '../runtime/adapters.js';

/** How an answer is checked. Every grader is deterministic: no model judges another. */
export type Grader =
  /** GSM8K: the number on the final "Answer:" line. */
  | { kind: 'number'; answer: number }
  /** CRUXEval: the returned Python value, compared as a literal. */
  | { kind: 'literal'; answer: string }
  /** IFEval: every instruction must hold (strict). */
  | { kind: 'ifeval'; checks: { id: string; args: Record<string, unknown> }[] }
  /** BFCL: one call to the named function; each argument must be one of the accepted values ("" = may be omitted). */
  | { kind: 'tool-call'; name: string; args: Record<string, unknown[]> }
  /** SQuAD: the answer span, or a short answer containing it. */
  | { kind: 'span'; answers: string[] };

export interface BenchItem {
  id: string;
  category: BenchCategory;
  source: { dataset: string; split: string; row: number | string; license: string; url: string };
  prompt: string;
  tools?: ToolSpec[];
  grade: Grader;
}

/** Generated by `pnpm --filter @app/server bench:sample`; see backend/bench/README.md. */
export const SUITE_FILE = path.resolve(__dirname, '../../bench/suite.json');

let cached: { generatedAt: string; items: BenchItem[] } | undefined;
const suiteFile = () => cached ??= JSON.parse(readFileSync(SUITE_FILE, 'utf8'));

export const loadSuite = (): BenchItem[] => suiteFile().items;
export const suiteGeneratedAt = (): string => suiteFile().generatedAt;

/** The first `perCategory` items of each chosen category. */
export function selectItems(categories: BenchCategory[], perCategory: number, suite = loadSuite()): BenchItem[] {
  return categories.flatMap(category => suite.filter(item => item.category === category).slice(0, perCategory));
}
